import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig, type Plugin } from 'vite';

/**
 * Writes dist/sw.js after the build: client/sw/sw.js (hand-written) prefixed
 * with the precache list (index.html, hashed /assets/*, small icons, manifest)
 * and SW_VERSION, a hash of all of them. Only builds get a service worker; the
 * dev server never registers one (see src/pwa/pwa.ts).
 * WORLDS_SW_KILL=1 ships client/sw/sw-killswitch.js as /sw.js instead.
 */
const SHELL_EXTRAS = ['/manifest.json', '/favicon.svg', '/favicon-32.png', '/icon-192.png', '/badge-96.png', '/apple-touch-icon.png'];
function serviceWorker(): Plugin {
  let outDir = 'dist';
  return {
    name: 'worlds-sw',
    apply: 'build',
    configResolved(c) {
      outDir = resolve(c.root, c.build.outDir);
    },
    closeBundle() {
      const swDir = fileURLToPath(new URL('./sw', import.meta.url));
      if (process.env.WORLDS_SW_KILL === '1') {
        writeFileSync(join(outDir, 'sw.js'), readFileSync(join(swDir, 'sw-killswitch.js')));
        return;
      }
      const walk = (dir: string): string[] =>
        readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f)) : [join(dir, f)]));
      const assets = walk(join(outDir, 'assets')).map((f) => '/' + relative(outDir, f).split(sep).join('/'));
      const list = ['/index.html', ...assets.sort(), ...SHELL_EXTRAS.filter((p) => statSync(join(outDir, p), { throwIfNoEntry: false }))];
      const template = readFileSync(join(swDir, 'sw.js'), 'utf-8');
      const h = createHash('sha256').update(template);
      for (const p of list) h.update(p).update(readFileSync(join(outDir, p)));
      const version = h.digest('hex').slice(0, 12);
      const head = `// generated by vite.config.ts (worlds-sw) — do not edit dist/sw.js\nconst SW_VERSION = ${JSON.stringify(version)};\nconst PRECACHE = ${JSON.stringify(list, null, 1)};\n\n`;
      writeFileSync(join(outDir, 'sw.js'), head + template);
    },
  };
}

// Dev: Vite on 5180, game/API server on 5181. The browser always talks to the
// same origin (/api, /ws) and Vite forwards both, so phones on the LAN only
// need port 5180. xfwd adds X-Forwarded-For/Proto/Host (trusted by the server
// only from 127.0.0.1); changeOrigin stays off so the Origin/Host same-origin
// check on the server sees the real host. Production doesn't use Vite: the
// Node server serves client/dist itself (see deploy/README.md).
const serverTarget = process.env.WORLDS_SERVER ?? 'http://127.0.0.1:5181';
const proxy = {
  '/ws': { target: serverTarget, ws: true, changeOrigin: false, xfwd: true },
  '/api': { target: serverTarget, changeOrigin: false, xfwd: true },
};

export default defineConfig({
  plugins: [serviceWorker()],
  define: { __BUILD_TAG__: JSON.stringify(process.env.WORLDS_BUILD_TAG ?? '') },
  server: {
    host: '0.0.0.0',
    port: 5180,
    strictPort: true,
    allowedHosts: ['qt.log2u.me'],
    proxy,
    // ../shared holds the protocol used by both client and server.
    fs: { allow: ['..'] },
  },
  preview: { host: '0.0.0.0', port: 5180, strictPort: true, allowedHosts: ['qt.log2u.me'], proxy },
  build: { sourcemap: false, chunkSizeWarningLimit: 900 },
});
